-- Bootstrap schema, keys, sequences, and numbering triggers for KINSURE.
CREATE TABLE USERSINS (
    USERNAME VARCHAR2(20 BYTE) NOT NULL,
    PASSWORD_HASH VARCHAR2(255 BYTE) NOT NULL,
    FULL_NAME VARCHAR2(100 BYTE) NOT NULL,
    EMAIL VARCHAR2(100 BYTE) NOT NULL,
    ROLE VARCHAR2(20 BYTE) NOT NULL,
    IS_ACTIVE NUMBER(1, 0) DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_USERSINS PRIMARY KEY (USERNAME),
    CONSTRAINT CK_USERSINS_ACTIVE CHECK (IS_ACTIVE IN (0, 1))
);

CREATE TABLE PRODUCT_TYPES (
    PRODUCT_TYPE VARCHAR2(5 BYTE) NOT NULL,
    PRODUCT_NAME VARCHAR2(50 BYTE) NOT NULL,
    CONSTRAINT PK_PRODUCT_TYPES PRIMARY KEY (PRODUCT_TYPE)
);

CREATE TABLE CUSTOMERS (
    TCKN_VKN VARCHAR2(11 BYTE) NOT NULL,
    FIRST_NAME VARCHAR2(50 BYTE) NOT NULL,
    LAST_NAME VARCHAR2(50 BYTE) NOT NULL,
    EMAIL VARCHAR2(100 BYTE),
    PHONE VARCHAR2(20 BYTE) NOT NULL,
    BIRTH_DATE DATE,
    GENDER CHAR(1 BYTE),
    ADDRESS VARCHAR2(500 BYTE),
    CREATED_BY VARCHAR2(20 BYTE) NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_CUSTOMERS PRIMARY KEY (TCKN_VKN),
    CONSTRAINT CK_CUSTOMERS_GENDER CHECK (GENDER IN ('E', 'K', 'X')),
    CONSTRAINT FK_CUSTOMERS_CREATED_BY FOREIGN KEY (CREATED_BY)
        REFERENCES USERSINS (USERNAME)
);

CREATE TABLE POLICIES (
    POLICY_ID NUMBER NOT NULL,
    POLICY_NO VARCHAR2(30 BYTE),
    TCKN_VKN VARCHAR2(11 BYTE) NOT NULL,
    PRODUCT_TYPE VARCHAR2(5 BYTE) NOT NULL,
    START_DATE DATE NOT NULL,
    END_DATE DATE NOT NULL,
    PREMIUM_AMOUNT NUMBER(15, 2) NOT NULL,
    STATUS VARCHAR2(20 BYTE) DEFAULT 'ACTIVE',
    CREATED_BY VARCHAR2(20 BYTE) NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_POLICIES PRIMARY KEY (POLICY_ID),
    CONSTRAINT FK_POLICIES_CUSTOMER FOREIGN KEY (TCKN_VKN)
        REFERENCES CUSTOMERS (TCKN_VKN),
    CONSTRAINT FK_POLICIES_PRODUCT FOREIGN KEY (PRODUCT_TYPE)
        REFERENCES PRODUCT_TYPES (PRODUCT_TYPE),
    CONSTRAINT FK_POLICIES_CREATED_BY FOREIGN KEY (CREATED_BY)
        REFERENCES USERSINS (USERNAME),
    CONSTRAINT CK_POLICIES_DATES CHECK (END_DATE > START_DATE),
    CONSTRAINT CK_POLICIES_PREMIUM CHECK (PREMIUM_AMOUNT >= 0)
);

CREATE TABLE CLAIMS (
    CLAIM_ID NUMBER NOT NULL,
    CLAIM_NO VARCHAR2(30 BYTE) NOT NULL,
    POLICY_ID NUMBER NOT NULL,
    INCIDENT_DATE DATE NOT NULL,
    CLAIM_DATE DATE NOT NULL,
    CLAIM_AMOUNT NUMBER(15, 2) NOT NULL,
    PAID_AMOUNT NUMBER(15, 2) DEFAULT 0,
    STATUS VARCHAR2(20 BYTE) DEFAULT 'OPEN',
    DESCRIPTION VARCHAR2(1000 BYTE),
    CREATED_BY VARCHAR2(20 BYTE) NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_CLAIMS PRIMARY KEY (CLAIM_ID),
    CONSTRAINT UQ_CLAIMS_CLAIM_NO UNIQUE (CLAIM_NO),
    CONSTRAINT FK_CLAIMS_POLICY FOREIGN KEY (POLICY_ID)
        REFERENCES POLICIES (POLICY_ID),
    CONSTRAINT FK_CLAIMS_CREATED_BY FOREIGN KEY (CREATED_BY)
        REFERENCES USERSINS (USERNAME),
    CONSTRAINT CK_CLAIMS_AMOUNTS CHECK (CLAIM_AMOUNT >= 0 AND PAID_AMOUNT >= 0)
);

CREATE SEQUENCE SEQ_POLICIES START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_CLAIMS START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER TRG_POLICIES_BI
BEFORE INSERT ON POLICIES
FOR EACH ROW
DECLARE
    v_policy_id NUMBER;
BEGIN
    IF :NEW.POLICY_ID IS NULL THEN
        SELECT SEQ_POLICIES.NEXTVAL INTO v_policy_id FROM DUAL;
        :NEW.POLICY_ID := v_policy_id;
    ELSE
        v_policy_id := :NEW.POLICY_ID;
    END IF;

    IF :NEW.POLICY_NO IS NULL THEN
        :NEW.POLICY_NO := CASE :NEW.PRODUCT_TYPE
            WHEN 'K' THEN TO_CHAR(v_policy_id + 10000)
            WHEN 'T' THEN TO_CHAR(v_policy_id + 20000)
            WHEN 'YE' THEN TO_CHAR(v_policy_id + 30000)
            WHEN 'YB' THEN TO_CHAR(v_policy_id + 40000)
            WHEN 'KO' THEN TO_CHAR(v_policy_id + 90000)
            ELSE 'POL-' || TO_CHAR(v_policy_id)
        END;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_CLAIMS_BI
BEFORE INSERT ON CLAIMS
FOR EACH ROW
DECLARE
    v_claim_id NUMBER;
    v_product_type VARCHAR2(5);
BEGIN
    SELECT PRODUCT_TYPE
    INTO v_product_type
    FROM POLICIES
    WHERE POLICY_ID = :NEW.POLICY_ID;

    IF :NEW.CLAIM_ID IS NULL THEN
        SELECT SEQ_CLAIMS.NEXTVAL INTO v_claim_id FROM DUAL;
        :NEW.CLAIM_ID := v_claim_id;
    ELSE
        v_claim_id := :NEW.CLAIM_ID;
    END IF;

    IF :NEW.CLAIM_NO IS NULL THEN
        :NEW.CLAIM_NO := TO_CHAR(SYSDATE, 'YYYY') || ' ' ||
                         v_product_type || ' ' || TO_CHAR(v_claim_id);
    END IF;
END;
/
